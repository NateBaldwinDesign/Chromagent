import type { Theme, ThemeMode } from "../theme/generateTheme";

export interface CssOptions {
  /** Custom property prefix. Default "color", giving names like --color-brand-500. */
  prefix?: string;
  /** Write the default mode inside a Tailwind v4 `@theme` block so utilities like `bg-brand-900` work. */
  tailwind?: boolean;
}

function roleTarget(ref: string, prefix: string) {
  const [group, item] = ref.split(".");
  return group === "surface" ? `--${prefix}-surface-${item}` : `--${prefix}-${group}-${item}`;
}

/** The CSS custom properties for one mode, in output order. Role references point at their scale or surface variable. */
export function cssVariables(mode: ThemeMode, prefix = "color"): Record<string, string> {
  if (typeof prefix !== "string" || !/^[a-z][a-z0-9-]*$/i.test(prefix))
    throw new Error(`The CSS variable prefix must start with a letter and use only letters, numbers, and dashes (got ${JSON.stringify(prefix)}).`);
  const vars: Record<string, string> = {};
  for (const [scale, steps] of Object.entries(mode.scales))
    for (const [step, value] of Object.entries(steps)) vars[`--${prefix}-${scale}-${step}`] = value.css;
  for (const [name, value] of Object.entries(mode.surfaces)) vars[`--${prefix}-surface-${name}`] = value.css;
  // Roles are repeated in every block so they follow the mode wherever data-theme is set.
  for (const [role, value] of Object.entries(mode.roles))
    vars[`--${prefix}-${role}`] = value.ref ? `var(${roleTarget(value.ref, prefix)})` : value.css;
  return vars;
}

function declarations(mode: ThemeMode, prefix: string, indent: string, colorScheme = true) {
  const lines = colorScheme ? [`${indent}color-scheme: ${mode.settings.backgroundLightness < 0.5 ? "dark" : "light"};`] : [];
  for (const [name, value] of Object.entries(cssVariables(mode, prefix))) lines.push(`${indent}${name}: ${value};`);
  return lines.join("\n");
}

const block = (selector: string, body: string, indent = "") => `${indent}${selector} {\n${body}\n${indent}}`;

const scheme = (mode: ThemeMode) => (mode.settings.backgroundLightness < 0.5 ? "dark" : "light");

/** "more" or "less" when a mode is a contrast variant, from its media query or its name. */
function contrastLevel(mode: ThemeMode): "more" | "less" | undefined {
  if (mode.media?.includes("prefers-contrast: more")) return "more";
  if (mode.media?.includes("prefers-contrast: less")) return "less";
  const words = mode.name.toLowerCase().split(/[-_\s]+/);
  if (!words.includes("contrast")) return undefined;
  if (words.some((w) => ["high", "more", "increased", "max"].includes(w))) return "more";
  if (words.some((w) => ["low", "less", "reduced", "min"].includes(w))) return "less";
  return undefined;
}

/**
 * CSS custom properties for every mode. The default mode is on :root. Each other mode
 * applies with [data-theme="name"], and also automatically through its media query
 * (for example prefers-color-scheme: dark) unless a data-theme is set.
 * Contrast variants (such as dark-high-contrast) also apply with data-contrast="more" or "less",
 * combined with data-theme="dark" or the system color scheme. data-contrast="normal" opts out.
 */
export function toCss(theme: Theme, options: CssOptions = {}) {
  const prefix = options.prefix ?? "color";
  const parts: string[] = [`/* Generated by chromagentic. Contrast formula: ${theme.formula}. Gamut: ${theme.gamut}. */`];
  const defaultMode = theme.modes[theme.defaultMode];
  if (options.tailwind) {
    // Tailwind writes @theme variables to :root and builds utilities from them.
    parts.push(block("@theme", declarations(defaultMode, prefix, "  ", false)));
    parts.push(block(":root", `  color-scheme: ${scheme(defaultMode)};`));
    parts.push(block(`[data-theme="${theme.defaultMode}"]`, declarations(defaultMode, prefix, "  ")));
  } else {
    parts.push(block(`:root, [data-theme="${theme.defaultMode}"]`, declarations(defaultMode, prefix, "  ")));
  }
  const modes = Object.values(theme.modes);
  const others = modes.filter((mode) => mode.name !== theme.defaultMode);
  // A contrast variant pairs with the plain mode of the same color scheme (dark-high-contrast → dark).
  const baseOf = (mode: ThemeMode) => {
    const candidates = modes.filter((m) => m !== mode && !contrastLevel(m) && scheme(m) === scheme(mode));
    return candidates.find((m) => mode.name.startsWith(`${m.name}-`)) ?? candidates[0];
  };
  const variants = others.filter((mode) => contrastLevel(mode) && baseOf(mode));
  const auto = (mode: ThemeMode) => (variants.includes(mode) ? ":root:not([data-theme]):not([data-contrast])" : ":root:not([data-theme])");
  // Fewer conditions first, so combined queries (dark and high contrast) win when both match.
  const withMedia = others
    .filter((mode) => mode.media)
    .sort((a, b) => a.media!.split(" and ").length - b.media!.split(" and ").length);
  for (const mode of withMedia)
    parts.push(block(`@media ${mode.media}`, block(auto(mode), declarations(mode, prefix, "    "), "  ")));
  for (const mode of others) {
    const pair = variants.includes(mode) ? `, [data-theme="${baseOf(mode)!.name}"][data-contrast="${contrastLevel(mode)}"]` : "";
    parts.push(block(`[data-theme="${mode.name}"]${pair}`, declarations(mode, prefix, "  ")));
  }
  // Light variants first so the dark ones win inside the dark media query.
  for (const mode of [...variants].sort((a, b) => Number(scheme(a) === "dark") - Number(scheme(b) === "dark"))) {
    const level = contrastLevel(mode)!;
    const base = baseOf(mode)!;
    const chosen = `:root:not([data-theme])[data-contrast="${level}"]`;
    parts.push(
      scheme(mode) === "dark"
        ? block("@media (prefers-color-scheme: dark)", block(chosen, declarations(mode, prefix, "    "), "  "))
        : block(chosen, declarations(mode, prefix, "  ")),
    );
    parts.push(block(`@media (prefers-contrast: ${level})`, block(`[data-theme="${base.name}"]:not([data-contrast])`, declarations(mode, prefix, "    "), "  ")));
  }
  return `${parts.join("\n\n")}\n`;
}
